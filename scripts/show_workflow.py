def _prompt_text(song_stem: str, venue_dir: str) -> str:
    venue = Path(venue_dir).as_posix()
    return (
        f'Build a show for "{song_stem}" using the full workflow.\n'
        f"- Venue: `{venue}`\n"
        "- Use phrase-aware planning as a hard layer from song-data segments.\n"
        "- Enforce research gate: artist branding + song-title inspiration + sources.\n"
        "- Build creative context from the approved brief and feed brand_tokens + creative_directives into phrase-technique selection.\n"
        "- Keep references/creativity.md venue-agnostic; put venue specifics under venue references.\n"
        f"- Update/create brief in `{venue}/shows/notes/` and generator in `{venue}/generators/`.\n"
        f"- Generate `.qxw` in `{venue}/shows/` and run validators.\n"
    )


def cmd_next(venue_dir: str, limit: int) -> int:
    _validate_venue(venue_dir)
    stems = _song_stems()
    if not stems:
        print("No songs-data JSON files found.")
        return 1

    missing: List[str] = []
    for stem in stems:
        if not _show_path(venue_dir, stem).exists():
            missing.append(stem)

    if not missing:
        print("All songs-data entries already have shows for this venue.")
        return 0

    print(f"Next songs without shows ({venue_dir}):")
    for stem in missing[: max(1, limit)]:
        print(f"- {stem}")
    print("\nUse:")
    print(f'python3 scripts/show_workflow.py scaffold --song "{missing[0]}" --venue {venue_dir}')
    return 0


def cmd_status(venue_dir: str, limit: int) -> int:
    _validate_venue(venue_dir)
    stems = _song_stems()
    if not stems:
        print("No songs-data JSON files found.")
        return 1

    rows: List[Tuple[str, str, str, str]] = []
    for stem in stems:
        gen = _generator_path(venue_dir, stem).exists()
        show = _show_path(venue_dir, stem).exists()
        brief_json, _ = _brief_paths(venue_dir, stem)
        brief_exists = brief_json.exists()
        approved, _ = _brief_is_approved(stem, venue_dir) if brief_exists else (False, "missing")
        rows.append(
            (
                stem,
                "yes" if gen else "no",
                "yes" if show else "no",
                "approved" if approved else ("draft" if brief_exists else "missing"),
            )
        )

    print("song | generator | show | brief")
    print("---|---|---|---")
    for row in rows[: max(1, limit)]:
        print(f"{row[0]} | {row[1]} | {row[2]} | {row[3]}")
    print(f"\nTotal songs: {len(rows)}")
    return 0


def cmd_scaffold(song_query: str, venue_dir: str, overwrite_generator: bool, print_prompt: bool) -> int:
    _validate_venue(venue_dir)
    song_stem = _resolve_song(song_query)
    bpm = _load_bpm(song_stem)

    brief_json, brief_md = _brief_paths(venue_dir, song_stem)
    approved, brief_message = _brief_is_approved(song_stem, venue_dir)
    # load_and_validate_brief creates stubs when missing, so paths now exist.

    generator_path = _generator_path(venue_dir, song_stem)
    generator_path.parent.mkdir(parents=True, exist_ok=True)
    if generator_path.exists() and not overwrite_generator:
        generator_action = "kept"
    else:
        generator_path.write_text(_generator_template(song_stem, bpm), encoding="utf-8")
        generator_action = "written"

    show_path = _show_path(venue_dir, song_stem)

    print(f"Song: {song_stem}")
    print(f"Venue: {venue_dir}")
    print(f"Brief JSON: {brief_json.relative_to(ROOT)}")
    print(f"Brief MD:   {brief_md.relative_to(ROOT)}")
    print(f"Generator:  {generator_path.relative_to(ROOT)} ({generator_action})")
    print(f"Output QXW: {show_path.relative_to(ROOT)}")
    print(f"BPM: {bpm}")
    if approved:
        print("Brief status: approved")
    else:
        print(f"Brief status: draft/not ready ({brief_message})")
        print("Next: fill brief JSON, set status=approved, then run the generator.")

    if print_prompt:
        print("\nPrompt for Codex:")
        print(_prompt_text(song_stem, venue_dir))

    return 0


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Show workflow helper")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_next = sub.add_parser("next", help="List songs-data entries missing shows")
    p_next.add_argument("--venue", default=DEFAULT_VENUE, help="Venue dir relative to project root")
    p_next.add_argument("--limit", type=int, default=10, help="Number of songs to print")

    p_status = sub.add_parser("status", help="Show generator/show/brief status")
    p_status.add_argument("--venue", default=DEFAULT_VENUE, help="Venue dir relative to project root")
    p_status.add_argument("--limit", type=int, default=30, help="Max rows to print")

    p_scaffold = sub.add_parser("scaffold", help="Create brief stubs + generator scaffold for a song")
    p_scaffold.add_argument("--song", required=True, help="Song title/stem or partial match")
    p_scaffold.add_argument("--venue", default=DEFAULT_VENUE, help="Venue dir relative to project root")
    p_scaffold.add_argument("--overwrite-generator", action="store_true", help="Overwrite existing generator")
    p_scaffold.add_argument("--no-prompt", action="store_true", help="Do not print Codex prompt")

    return parser


def main(argv: Iterable[str] | None = None) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)

    try:
        if args.cmd == "next":
            return cmd_next(venue_dir=args.venue, limit=max(1, args.limit))
        if args.cmd == "status":
            return cmd_status(venue_dir=args.venue, limit=max(1, args.limit))
        if args.cmd == "scaffold":
            return cmd_scaffold(
                song_query=args.song,
                venue_dir=args.venue,
                overwrite_generator=bool(args.overwrite_generator),
                print_prompt=not bool(args.no_prompt),
            )
        raise ValueError(f"Unsupported command: {args.cmd}")
    except Exception as exc:
        print(f"Error: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
