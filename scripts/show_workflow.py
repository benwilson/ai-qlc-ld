def _song_stems() -> List[str]:
    return sorted(path.stem for path in SONGS_DATA_DIR.glob("*.json"))


def _resolve_song(song_query: str) -> str:
    stems = _song_stems()
    if not stems:
        raise ValueError(f"No song data found in {SONGS_DATA_DIR}")

    if song_query in stems:
        return song_query

    exact_casefold = [stem for stem in stems if stem.casefold() == song_query.casefold()]
    if len(exact_casefold) == 1:
        return exact_casefold[0]
    if len(exact_casefold) > 1:
        raise ValueError(f"Ambiguous song query: {song_query}")

    partial = [stem for stem in stems if song_query.casefold() in stem.casefold()]
    if len(partial) == 1:
        return partial[0]
    if not partial:
        raise ValueError(f"No song match for: {song_query}")
    raise ValueError(
        "Song query matched multiple songs. Be more specific:\n"
        + "\n".join(f"- {stem}" for stem in partial[:12])
    )


def _validate_venue(venue_dir: str) -> Path:
    venue = (ROOT / venue_dir).resolve()
    if not venue.exists() or not venue.is_dir():
        raise ValueError(f"Venue directory does not exist: {venue_dir}")
    if not (venue / "generators").exists():
        raise ValueError(f"Missing generators directory in venue: {venue_dir}")
    if not (venue / "shows").exists():
        raise ValueError(f"Missing shows directory in venue: {venue_dir}")
    return venue


def _generator_path(venue_dir: str, song_stem: str) -> Path:
    return ROOT / venue_dir / "generators" / f"{song_stem}.py"


def _show_path(venue_dir: str, song_stem: str) -> Path:
    return ROOT / venue_dir / "shows" / f"{song_stem}.qxw"


def _brief_paths(venue_dir: str, song_stem: str) -> Tuple[Path, Path]:
    return resolve_brief_paths(project_root=ROOT, song_title=song_stem, venue_dir=venue_dir)


def _brief_is_approved(song_stem: str, venue_dir: str) -> Tuple[bool, str]:
    try:
        load_and_validate_brief(song_title=song_stem, project_root=ROOT, venue_dir=venue_dir)
        return True, "approved"
    except Exception as exc:
        return False, str(exc)


def _load_bpm(song_stem: str) -> int:
    path = SONGS_DATA_DIR / f"{song_stem}.json"
    with path.open("r", encoding="utf-8") as handle:
        payload = json.load(handle)
    bpm = payload.get("bpm", 128)
    try:
        return int(round(float(bpm)))
    except Exception:
        return 128


